const DICTIONARIES: Record<string, Dictionary> = { en, es };

export type Translate = (key: MessageKey | `${string}`, vars?: Record<string, string | number>) => string;

export const LocaleContext = createContext<string>("en");

/** Maps a WHMCS language name ("spanish", "english") or code to a supported locale. */
export function resolveLocale(lang: string | undefined): string {
  const l = (lang || "").toLowerCase();
  if (l.startsWith("es") || l === "spanish" || l === "catalan") return "es";
  return "en";
}

export function useLocale(): string {
  return useContext(LocaleContext);
}

export function useT(): Translate {
  const locale = useLocale();
  return useCallback<Translate>(
    (key, vars) => {
      const dict = DICTIONARIES[locale] ?? en;
      const pluralKey = vars?.count === 1 ? (`${key}_one` as MessageKey) : null;
      let text = (pluralKey && dict[pluralKey]) || dict[key as MessageKey] || en[key as MessageKey] || key;
      if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
      return text;
    },
    [locale],
  );
}
